// Writes catalog.js: the small index (topics and Arena problems) that the pit-wall coach needs on every page,
// so pages that do not load the question banks can still plan. Run: npm run build:catalog
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export function buildCatalog() {
  const concept = require('../questions.js')
  const math = require('../math.js')
  const { problems } = require('../problems.js')
  const data = {
    modules: [...concept.modules.map((m) => ({ id: m.id, name: m.name, track: 'quiz' })), ...math.modules.map((m) => ({ id: m.id, name: m.name, track: 'math' }))],
    problems: problems.map((p) => ({ id: p.id, tier: p.tier, title: p.title })),
  }
  return `// Generated by scripts/build-catalog.mjs. Do not edit by hand.\n;(function (root, data) {\n  if (typeof module === 'object' && module.exports) module.exports = data\n  else root.CATALOG = data\n})(typeof self !== 'undefined' ? self : this, ${JSON.stringify(data, null, 1)})\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = buildCatalog()
  const file = path.join(root, 'catalog.js')
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text
    console.log(same ? 'catalog.js is up to date' : 'catalog.js is stale: run npm run build:catalog')
    process.exit(same ? 0 : 1)
  }
  fs.writeFileSync(file, text)
  console.log('wrote catalog.js')
}
