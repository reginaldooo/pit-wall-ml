// Writes headshots.js: driver photo URLs from OpenF1 (https://openf1.org), matched to the roster by last name.
// OpenF1 restricts the API during live sessions; run this between sessions, or set OPENF1_TOKEN for authenticated access.
// Run: npm run build:headshots
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const API = 'https://api.openf1.org/v1/drivers?session_key=latest'
const slug = (text) => text.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const lastName = (text) => slug(text).split('-').pop()

export function matchHeadshots(roster, apiDrivers) {
  const result = {}
  for (const person of roster.filter((p) => p.role === 'driver')) {
    const found = apiDrivers.filter((d) => d.full_name && d.headshot_url && lastName(d.full_name) === lastName(person.name))
    if (found.length === 1) result[person.id] = found[0].headshot_url.replace(/^http:/, 'https:')
  }
  return result
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const headers = process.env.OPENF1_TOKEN ? { Authorization: `Bearer ${process.env.OPENF1_TOKEN}` } : {}
  const res = await fetch(API, { headers })
  const body = await res.json()
  if (!res.ok || !Array.isArray(body)) {
    console.error(`OpenF1 refused the request (${res.status}): ${body.detail || JSON.stringify(body)}`)
    process.exit(1)
  }
  const { roster } = require('../moderators.js')
  const urls = matchHeadshots(roster, body)
  const missing = roster.filter((p) => p.role === 'driver' && !urls[p.id]).map((p) => p.name)
  const text = `// Generated by scripts/fetch-headshots.mjs from OpenF1. Do not edit by hand.\n;(function (root, factory) {\n  if (typeof module === 'object' && module.exports) module.exports = factory()\n  else root.Headshots = factory()\n})(typeof self !== 'undefined' ? self : this, function () {\n  return ${JSON.stringify(urls, null, 2).replace(/\n/g, '\n  ')}\n})\n`
  fs.writeFileSync(path.join(root, 'headshots.js'), text)
  console.log(`headshots.js: ${Object.keys(urls).length} photos${missing.length ? `; no photo for ${missing.join(', ')}` : ''}`)
}
